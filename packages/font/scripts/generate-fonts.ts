/**
 * Regenerates `src/fonts/*.ts` and `src/all.ts` from the vendored `.flf` files in `fonts/`.
 *
 *   bun packages/font/scripts/generate-fonts.ts
 *
 * Font files are decoded as Latin-1 (FIGlet reads bytes) and embedded verbatim, header
 * comments and credits included.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FONTS } from "./font-list";

const root = join(import.meta.dir, "..");

function literal(source: string): string {
  let out = "";
  const chars = Array.from(source);
  for (const [i, ch] of chars.entries()) {
    const code = ch.codePointAt(0) as number;
    if (ch === "\\") out += "\\\\";
    else if (ch === "`") out += "\\`";
    else if (ch === "$" && chars[i + 1] === "{") out += "\\$";
    else if (ch === "\n" || (code >= 0x20 && code <= 0x7e)) out += ch;
    else out += `\\u${code.toString(16).padStart(4, "0")}`;
  }
  return "`" + out + "`";
}

for (const font of FONTS) {
  const bytes = readFileSync(join(root, "fonts", `${font.id}.flf`));
  const source = new TextDecoder("latin1").decode(bytes);
  const code = `// Generated by scripts/generate-fonts.ts from fonts/${font.id}.flf (FIGlet 2.2.5). Do not edit.
// ${font.name}: BSD-3-Clause FIGlet distribution font. Credits are kept verbatim below; see LICENSES/FIGLET.txt.
import { defineFont, type FigletFont } from "../parse";

/** The ${font.name} FIGfont. ${font.description} */
export const ${font.exportName}: FigletFont = /* @__PURE__ */ defineFont(${JSON.stringify(font.name)}, ${literal(source)});
`;
  writeFileSync(join(root, "src", "fonts", `${font.id}.ts`), code);
}

const all = `// Generated by scripts/generate-fonts.ts. Do not edit.
// Every bundled font. Prefer \`@textjs/font/<name>\` imports so only the fonts you use ship.
import type { FigletFont } from "./parse";
${FONTS.map((f) => `import { ${f.exportName} } from "./fonts/${f.id}";`).join("\n")}

export { ${FONTS.map((f) => f.exportName).join(", ")} };

export interface BundledFont {
  /** Module name: \`import { ... } from "@textjs/font/<id>"\`. */
  readonly id: string;
  readonly exportName: string;
  readonly font: FigletFont;
  readonly description: string;
}

export const BUNDLED_FONTS: readonly BundledFont[] = [
${FONTS.map((f) => `  { id: ${JSON.stringify(f.id)}, exportName: ${JSON.stringify(f.exportName)}, font: ${f.exportName}, description: ${JSON.stringify(f.description)} },`).join("\n")}
];
`;
writeFileSync(join(root, "src", "all.ts"), all);
console.log(`Generated ${FONTS.length} fonts.`);
