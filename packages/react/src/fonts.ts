export type AsciiFontName = "block" | "compact";

export const ASCII_FONT_CHARS: string = Object.keys(G).join("");

function glyph(ch: string): readonly string[] {
  return G[ch] ?? G[ch.toUpperCase()] ?? G[" "]!;
}

/** Render text into rows of block characters. Unsupported characters become spaces. */
export function renderAsciiFont(text: string, font: AsciiFontName = "block", letterSpacing = 1): string[] {
  const chars = Array.from(text);
  const pixels: string[] = ["", "", "", "", ""];
  chars.forEach((ch, idx) => {
    const g = glyph(ch);
    for (let r = 0; r < 5; r++) pixels[r] += (g[r] as string) + (idx < chars.length - 1 ? ".".repeat(letterSpacing) : "");
  });
  if (font === "block") return pixels.map((row) => row.replace(/#/g, "█").replace(/\./g, " ").replace(/\s+$/, ""));
  const out: string[] = [];
  for (let r = 0; r < 5; r += 2) {
    const top = pixels[r] as string;
    const bottom = pixels[r + 1] ?? "";
    let line = "";
    for (let c = 0; c < top.length; c++) {
      const t = top[c] === "#";
      const b = bottom[c] === "#";
      line += t && b ? "█" : t ? "▀" : b ? "▄" : " ";
    }
    out.push(line.replace(/\s+$/, ""));
  }
  return out;
}
