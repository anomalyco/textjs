"""Vendor the documented binding defaults (including disabled commands) without shipping CLI code."""
import json,re,sys
from pathlib import Path
source=Path(sys.argv[1])/'services/site/src/docs/content/cli/keybinds.mdx'
catalog={}
for line in source.read_text().splitlines():
    if line.startswith('## '): group=line[3:]
    m=re.match(r'^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`.*?\|\s*([^|]+)\s*\|',line)
    if m:
        id,keys,title=m.groups()
        if keys.startswith('{'):keys=json.loads(keys)['key']
        catalog[id]=[keys,title.strip(),group]
dest=Path(__file__).resolve().parents[3]/'packages/opencode/src/key-defaults.ts'
dest.write_text('// Generated by apps/opencode-console/scripts/key-catalog.py from the native CLI keybind reference.\nexport const keyDefaults: Readonly<Record<string, readonly string[]>> = '+json.dumps(catalog,ensure_ascii=False,indent=0)+';\n')
