/**
 * Writes `src/site/logo-console.ts`, the string behind the logo menu's "Copy Logo as console.log".
 *
 *   bun scripts/generate-logo-console.ts
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { encodeLogoConsoleLog } from "../src/site/logo-console-gen";

const code = await encodeLogoConsoleLog("chromium");
// Firefox and Safari keep %c spans inline, so they get the inline-console CSS (one profile covers both).
const inline = await encodeLogoConsoleLog("firefox");
const out = join(import.meta.dirname, "..", "src", "site", "logo-console.ts");
writeFileSync(
  out,
  `// Generated by scripts/generate-logo-console.ts. Do not edit.\nexport const LOGO_CONSOLE_LOG = ${JSON.stringify(code)};\nexport const LOGO_CONSOLE_LOG_INLINE = ${JSON.stringify(inline)};\n`,
);
console.log(`wrote ${out} (${code.length} + ${inline.length} chars)`);
